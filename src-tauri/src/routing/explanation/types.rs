// ============================================================================
// Nano Route - Routing Explanation Types & DTOs
// File: src-tauri/src/routing/explanation/types.rs
// ============================================================================
// Authoritative data types for route explainability, candidate score breakdowns,
// task analysis summaries, SLM confidence semantics, and selection margins.
// Strictly read-only: explains routing decisions without altering them.
// ============================================================================

use serde::{Deserialize, Serialize};

pub const DEFAULT_EXPLANATION_SCHEMA_VERSION: &str = "1.0";

/// Selected provider and model descriptor formatted for explainability presentation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SelectedRouteExplanation {
    pub provider_id: String,
    pub provider_name: String,
    pub model_id: String,
    pub model_name: String,
    pub is_local: bool,
    pub context_window: Option<u32>,
}

/// Task capability requirement compared against the selected model's declared capabilities.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TaskRequirementExplanation {
    pub capability: String,
    pub label: String,
    pub is_matched_by_selected_model: bool,
}

/// Summary of the local SLM task analysis results (Step 28).
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct TaskAnalysisSummary {
    pub primary_intent: String,
    pub intent_label: String,
    pub intent_confidence: f64,
    pub complexity: String,
    pub complexity_label: String,
    pub complexity_score: f64,
    pub domains: Vec<String>,
    pub required_capabilities: Vec<TaskRequirementExplanation>,
    pub is_ambiguous: bool,
    pub ambiguity_level: String,
    pub completeness: String,
}

/// Individual scoring dimension with normalized score, policy weight, and explanation.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScoreDimensionExplanation {
    pub key: String,
    pub label: String,
    pub score: f64,
    pub weight_percent: Option<f64>,
    pub weighted_contribution: Option<f64>,
    pub explanation: String,
    pub status: String,
}

/// Score modification, bonus, or penalty applied during candidate scoring.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScoreAdjustmentExplanation {
    pub dimension: String,
    pub delta: f64,
    pub reason: String,
}

/// Detailed candidate suitability score breakdown across all analytical dimensions.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ScoreBreakdownExplanation {
    pub overall_score: Option<f64>,
    pub dimensions: Vec<ScoreDimensionExplanation>,
    pub adjustments: Vec<ScoreAdjustmentExplanation>,
}

/// Triad of distinct confidence concepts with explicit semantics.
/// Strictly distinguishes SLM classifier confidence, routing fit score, and selection margin.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ConfidenceSummaryExplanation {
    /// What the local SLM classifier reported about its own analysis (Step 27).
    pub slm_confidence: Option<f64>,
    /// High (>=0.80), Medium (0.50-0.79), Low (<0.50), or Unknown.
    pub slm_confidence_level: String,
    /// Suitability score generated by Nano Route's 11-factor scoring engine (Step 29).
    pub routing_fit: Option<f64>,
    /// Score difference between selected candidate and next eligible alternative.
    pub selection_margin: Option<f64>,
    /// Human-readable explanation clarifying what the confidence represents and does NOT represent.
    pub description: String,
}

/// Difference between the selected candidate's score and the relevant runner-up alternative.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct SelectionMarginExplanation {
    pub margin: Option<f64>,
    pub runner_up_model: Option<String>,
    pub runner_up_score: Option<f64>,
    pub description: String,
}

/// Alternative provider/model candidate evaluated during candidate scoring.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct AlternativeCandidateExplanation {
    pub rank: usize,
    pub provider_id: String,
    pub provider_name: String,
    pub model_id: String,
    pub display_name: String,
    pub score: Option<f64>,
    pub is_eligible: bool,
    pub ineligibility_reason: Option<String>,
    pub status: String,
}

/// Factor or constraint from user preferences or routing policy that affected route selection.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct PolicyFactorExplanation {
    pub factor: String,
    pub label: String,
    pub description: String,
}

/// Provenance trace linking an explanation component to its analytical source.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct ExplanationEvidence {
    pub source: String,
    pub label: String,
    pub detail: String,
}

/// Complete, structured route explanation DTO returned across the Tauri IPC boundary.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct RoutingExplanation {
    pub schema_version: String,
    pub scoring_algorithm_version: String,
    pub policy_version: String,
    pub classifier_version: Option<String>,
    pub message_id: Option<String>,
    pub session_id: Option<String>,
    pub selection_mode: String,
    pub summary: String,
    pub decision_reason: String,
    pub is_historical: bool,
    pub selected_route: SelectedRouteExplanation,
    pub task_summary: Option<TaskAnalysisSummary>,
    pub score_breakdown: Option<ScoreBreakdownExplanation>,
    pub confidence_summary: ConfidenceSummaryExplanation,
    pub selection_margin: Option<SelectionMarginExplanation>,
    pub alternatives: Vec<AlternativeCandidateExplanation>,
    pub policy_factors: Vec<PolicyFactorExplanation>,
    pub evidence: Vec<ExplanationEvidence>,
    pub generated_at_ms: u64,
}

